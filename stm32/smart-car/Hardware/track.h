/**
 ******************************************************************************
 * @file    track.h
 * @brief   8 路红光灰度模拟分时循迹模块读取（感为科技，74HC4051 多路复用）
 *          接线：AD0=PB12, AD1=PB13, AD2=PB14（通道选择输出）
 *                OUT=PB0（ADC1_IN8 模拟输入）
 *                EN 悬空（默认使能），+5V/GND 接 TB6612
 ******************************************************************************
 */
#ifndef __TRACK_H
#define __TRACK_H

#include "stm32f10x.h"

/*
 * ============================================================================
 *  黑白阈值（必须实测调整！）
 *  12 位 ADC 范围 0~4095：
 *    - 白底反射强 → ADC 值高（通常 3000+）
 *    - 黑线反射弱 → ADC 值低（通常 1000 以下）
 *  取白底和黑线读数的中间值作为阈值，默认 2000 仅作参考。
 *  实测方法：上电后用串口打印 8 路 ADC 值，分别对着白纸和黑胶带看数值。
 * ============================================================================
 */
#define TRACK_THRESHOLD     2500

/**
 * @brief 初始化 8 路灰度模块：PB12/13/14 通道选择输出，PB0 ADC 模拟输入。
 */
void Track_Init(void);

/**
 * @brief 读取指定通道 (0~7) 的 ADC 原始值（0~4095）。
 * @param ch 通道号 0~7，对应从车左到车右的 8 个红外探头
 * @retval ADC 原始值
 */
uint16_t Track_ReadADC(uint8_t ch);

/**
 * @brief 计算当前车身相对黑线的"加权偏差"。
 * @retval 负值：黑线偏在车左边（车偏右，需要向左修）
 *         正值：黑线偏在车右边（车偏左，需要向右修）
 *         0  ：黑线居中，或 8 路都没压到线
 *         8 个传感器权重从左到右为 -4,-3,-2,-1,+1,+2,+3,+4
 */
int8_t Track_Error(void);

/**
 * @brief 判断是否到达"横线路口"（6 路以上同时压黑，用于识别直角转弯处）。
 * @retval 1=到达路口；0=未到达
 */
uint8_t Track_IsCross(void);

#endif /* __TRACK_H */
