/* ============================================================
 * 题号：18
 * 题名：数字字符
 * 考点：基本计算 · 字符与整型混用、scanf 格式串
 * 状态：❌ 本地实测未通过（2026-11-12）
 *
 * 实测说明：
 *   - 输入 `3 ,5`（逗号前有空格）时，`scanf("%d,%c")` 的逗号无法匹配空格，b 读不进去，输出乱码。
 *   - 输出是 `56, 8`，多了一个空格；题面样例为 `56,8`。
 *   - 待修：格式串改 `"%d ,%c"`；输出去掉空格。
 *
 * 本地测试用例：
 *   - 3,5   → 期望 56,8
 *   - 3 ,5 → 期望 56,8
 * ============================================================ */
#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>

int main()
{
	int a = 0,c = 0;
	char b = 0;

	scanf("%d,%c", &a, &b);

	c = a + b;

	printf("%d, %c",c, c);

	return 0;
}
