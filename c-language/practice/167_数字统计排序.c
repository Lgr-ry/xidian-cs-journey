/* ============================================================
 * 题号：167
 * 题名：数字统计排序
 * 考点：数组 · 桶计数 + 双层扫描排序
 * 状态：✅ 本地实测通过（2026-11-12）
 *
 * 实测说明：
 *   - 桶计数 arr[x]++ 得次数。
 *   - 不排序：外层次数 c 从 n 递减到 1，内层值 v 从 0 升到 1000，天然满足“次数降序、同次数值升序”。
 *   - 外层上界必须是 c>=1：写成 c>=0 会把所有未出现的值（次数 0）也打印出来。
 *
 * 本地测试用例：
 *   - 12 / 5 2 3 3 1 3 4 2 5 2 3 5 → 3 4, 2 3, 5 3, 1 1, 4 1
 *   - n=1 / 7 → 7 1
 *   - 5 / 3 3 3 3 3 → 3 5
 * ============================================================ */
#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>

int main()
{
	int n = 0,x = 0;
	scanf("%d", &n);

	int arr[1005] = { 0 };
	for (int i = 0; i < n; i++)
	{
		scanf("%d", &x);
		arr[x]++;
	}

	int c = n, v = 0;

	for (c = n; c >= 1; c--)
	{
		for (v = 0; v <= 1000; v++)
		{
			if (arr[v] == c)
			{
				printf("%d %d\n", v,c);
			}
		}
	}

	return 0;

}
