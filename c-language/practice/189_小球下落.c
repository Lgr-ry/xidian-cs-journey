/* ============================================================
 * 题号：189
 * 题名：小球下落
 * 考点：循环 · 累加与递推
 * 状态：✅ 本地实测通过（2026-11-12）
 *
 * 实测说明：
 *   - 第一次落地只算 100，之后每次加 2 倍反弹高度。
 *   - 输出格式 `S=%.3f h=%.3f` 与样例一致。
 *
 * 本地测试用例：
 *   - 10 → S=299.609 h=0.098
 * ============================================================ */
#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>

int main()
{
    int n;
    // 题目要求保留三位小数，所以用 double
    double sum = 100.0; // 第一次落地经过的路程就是 100
    double h = 100.0;   // 初始高度 100

    scanf("%d", &n);

    // 从第 1 次循环到第 n 次
    for (int i = 1; i <= n; i++)
    {
        h = h / 2.0; // 计算第 i 次落地后的反弹高度

        // 如果还没到最后一次落地，说明还要加上下一次的“上+下”路程
        if (i < n)
        {
            sum = sum + h * 2; // 距离累加
        }
    }

    // 题目样例的输出格式是 "S=... h=..."，注意里面的空格和等号
    printf("S=%.3f h=%.3f\n", sum, h);

    return 0;
}
