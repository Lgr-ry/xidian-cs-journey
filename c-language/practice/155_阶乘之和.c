/* ============================================================
 * 题号：155
 * 题名：阶乘之和
 * 考点：二重循环 · 嵌套计算与重置
 * 状态：✅ 本地实测通过（2026-11-12）
 *
 * 实测说明：
 *   - 外层每轮把 NN 重置为 1，再内层算 i!，最后累加。
 *   - N=7 → 7 5040 5913，与样例一致。
 *
 * 本地测试用例：
 *   - 7 → 7 5040 5913
 * ============================================================ */
#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>

int main()
{
	int N = 0, sum = 0;
	int NN = 1;
	int i = 0 , j = 0;

	scanf("%d", &N);

	for (i = 1; i <= N; i++)
	{
		NN = 1;

		for (j = 1; j <= i; j++)
		{
			NN = NN * j;
		}

		sum = sum + NN;
	}

	printf("%d %d %d\n", N, NN, sum);

	return 0;
}
